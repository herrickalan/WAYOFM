import fs from 'node:fs/promises';
import sharp from 'sharp';

await fs.mkdir('assets', { recursive: true });
const art = `<svg width="1024" height="1024" xmlns="http://www.w3.org/2000/svg"><rect width="1024" height="1024" fill="#087CFA"/><rect x="170" y="250" width="684" height="524" rx="30" fill="#16191B"/><text x="512" y="495" text-anchor="middle" font-family="DejaVu Sans, sans-serif" font-weight="bold" font-size="170" fill="white">WAYO</text><rect x="214" y="557" width="596" height="128" fill="#FF7A25"/><text x="512" y="651" text-anchor="middle" font-family="DejaVu Sans, sans-serif" font-weight="bold" font-size="90" fill="#16191B">104.3 FM</text></svg>`;
for (const [name, size] of [['app-icon', 1024], ['adaptive-icon', 1024], ['favicon', 64]]) {
  try { await fs.access(`assets/${name}.png`); }
  catch { await sharp(Buffer.from(art)).resize(size, size).png().toFile(`assets/${name}.png`); }
}
const optional = {};
for (const [key, file] of [['logo', 'weblogo_trans.png'], ['splash', 'wowee-progress.png']]) {
  try { await fs.access(`assets/${file}`); optional[key] = file; } catch { /* Use text branding until original files arrive. */ }
}
await fs.writeFile('src/branding.ts', `// Generated by npm run assets; includes only locally available original files.\nexport const branding = {\n${Object.entries(optional).map(([key, file]) => `  ${key}: require('../assets/${file}'),`).join('\n')}\n} as { logo?: number; splash?: number };\n`);
console.log('Branding assets:', Object.keys(optional).join(', ') || 'text fallback; original PNG files not installed');
